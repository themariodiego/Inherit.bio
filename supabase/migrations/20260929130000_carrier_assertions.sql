create table public.clinical_assertion_releases (
 release_id text primary key
  check (release_id ~ '^(clinvar-[0-9]{4}-(0[1-9]|1[0-2])|synthetic-[a-z0-9][a-z0-9-]{0,47})$'),
 source text not null check (source in ('clinvar','synthetic')),
 source_url text not null check (source_url ~ '^https://[^[:space:]]+$' and length(source_url)<=500),
 source_sha256 text not null check (source_sha256 ~ '^[0-9a-f]{64}$'),
 source_bytes bigint not null check (source_bytes>0),
 source_published_on date not null,
 retrieved_at timestamptz not null,
 extract_sha256 text not null check (extract_sha256 ~ '^[0-9a-f]{64}$'),
 gene_validity_url text not null check (gene_validity_url ~ '^https://[^[:space:]]+$' and length(gene_validity_url)<=500),
 gene_validity_sha256 text not null check (gene_validity_sha256 ~ '^[0-9a-f]{64}$'),
 gene_validity_created_on date not null,
 imported_at timestamptz not null default clock_timestamp(),
 retired_at timestamptz,
 check ((source='clinvar')=(release_id like 'clinvar-%')),
 check (retired_at is null or retired_at>=imported_at)
);
-- One current release per source: a new import retires the previous one.
create unique index clinical_assertion_releases_one_current
 on public.clinical_assertion_releases (source) where retired_at is null;

create table public.carrier_conditions (
 condition_id text primary key check (condition_id ~ '^(MONDO:[0-9]{7}|SYNTHETIC:[0-9]{1,7})$'),
 condition_name text not null check (condition_name=btrim(condition_name) and length(condition_name) between 1 and 80),
 gene_symbol text not null check (gene_symbol ~ '^[A-Z0-9][A-Z0-9-]{0,19}$'),
 -- X16.3: stored, not null, and one of five values. Where it is unknown,
 -- other or dominant the carrier rule refuses the arithmetic by name.
 inheritance_mode text not null
  check (inheritance_mode in ('autosomal_recessive','autosomal_dominant','x_linked','other','unknown')),
 gene_validity_classification text not null check (gene_validity_classification in
  ('Definitive','Strong','Moderate','Limited','Disputed','Refuted','No Known Disease Relationship')),
 gene_validity_classified_on date not null,
 gene_validity_url text not null check (gene_validity_url ~ '^https://[^[:space:]]+$' and length(gene_validity_url)<=500),
 -- Brief line 1332: a cited range, or "not established". Nothing is cited yet.
 penetrance_class text not null default 'unestablished'
  check (penetrance_class in ('high','moderate','low','unestablished')),
 penetrance_citation text check (penetrance_citation is null or length(penetrance_citation) between 3 and 300),
 -- ADR 0034 needs a serious-condition judgement; only a reviewer gives one.
 severity_class text not null default 'unreviewed' check (severity_class in ('serious','not_serious','unreviewed')),
 synthetic boolean not null default false,
 registry_revision bigint not null default 1 check (registry_revision>0),
 active boolean not null default false,
 active_review_id bigint,
 check ((penetrance_class='unestablished')=(penetrance_citation is null)),
 check (synthetic=(condition_id like 'SYNTHETIC:%')),
 check (active=(active_review_id is not null)),
 check (not active or severity_class<>'unreviewed'),
 unique (condition_id,gene_symbol)
);
-- The carrier rule answers per gene, so a gene names at most one condition.
create unique index carrier_conditions_one_per_gene on public.carrier_conditions (gene_symbol);

create table public.carrier_condition_reviews (
 review_id bigint generated always as identity primary key,
 condition_id text not null references public.carrier_conditions(condition_id) on delete restrict,
 registry_revision bigint not null check (registry_revision>0),
 decision text not null check (decision in ('activate','deactivate')),
 reviewer_name text not null check (reviewer_name=btrim(reviewer_name) and length(reviewer_name) between 3 and 120),
 reviewer_role text not null check (reviewer_role=btrim(reviewer_role) and length(reviewer_role) between 3 and 160),
 review_reference text not null check (review_reference=btrim(review_reference) and length(review_reference) between 3 and 500),
 severity_class text check (severity_class in ('serious','not_serious')),
 decided_at timestamptz not null default clock_timestamp(),
 check ((decision='activate')=(severity_class is not null))
);
alter table public.carrier_conditions add constraint carrier_conditions_active_review_fkey
 foreign key (active_review_id) references public.carrier_condition_reviews(review_id) on delete restrict;

create table public.clinical_assertions (
 assertion_id bigint generated always as identity primary key,
 release_id text not null references public.clinical_assertion_releases(release_id) on delete restrict,
 variation_id bigint not null check (variation_id>0),
 condition_id text not null,
 gene_symbol text not null,
 variant_name text not null check (length(variant_name) between 1 and 500),
 classification text not null check (classification in ('Pathogenic','Likely pathogenic','Pathogenic/Likely pathogenic',
  'Uncertain significance','Likely benign','Benign','Benign/Likely benign','Conflicting classifications of pathogenicity')),
 review_status text not null check (review_status in ('practice guideline','reviewed by expert panel',
  'criteria provided, multiple submitters, no conflicts','criteria provided, conflicting classifications',
  'criteria provided, single submitter','no assertion criteria provided','no classification provided')),
 review_stars smallint not null,
 conflict boolean not null,
 last_evaluated date,
 grch38_chrom smallint not null check (grch38_chrom between 1 and 22),
 grch38_pos integer not null check (grch38_pos>0),
 grch38_ref text not null,
 grch38_alt text not null,
 grch37_chrom smallint check (grch37_chrom between 1 and 22),
 grch37_pos integer check (grch37_pos>0),
 grch37_ref text,
 grch37_alt text,
 grch38_equivalents jsonb not null default '[]'::jsonb,
 foreign key (condition_id,gene_symbol) references public.carrier_conditions(condition_id,gene_symbol) on delete restrict,
 -- ClinVar's own table of stars (https://www.ncbi.nlm.nih.gov/clinvar/docs/review_status/).
 check (review_stars=case review_status when 'practice guideline' then 4 when 'reviewed by expert panel' then 3
  when 'criteria provided, multiple submitters, no conflicts' then 2 when 'criteria provided, single submitter' then 1
  when 'criteria provided, conflicting classifications' then 1 else 0 end),
 check (conflict or (review_status<>'criteria provided, conflicting classifications'
  and classification<>'Conflicting classifications of pathogenicity')),
 check (private.carrier_allele_key_valid_v1(grch38_ref,grch38_alt)),
 check ((grch37_chrom is null)=(grch37_pos is null) and (grch37_chrom is null)=(grch37_ref is null)
  and (grch37_chrom is null)=(grch37_alt is null)),
 check (grch37_ref is null or (grch37_chrom=grch38_chrom and private.carrier_allele_key_valid_v1(grch37_ref,grch37_alt)
  and length(grch37_ref)=length(grch38_ref) and length(grch37_alt)=length(grch38_alt))),
 check (private.carrier_equivalents_valid_v1(grch38_equivalents,grch38_pos,grch38_ref,grch38_alt)),
 unique (release_id,variation_id,condition_id),
 unique (release_id,grch38_chrom,grch38_pos,grch38_ref,grch38_alt)
);
create index clinical_assertions_condition_idx on public.clinical_assertions (condition_id,release_id);


create function private.carrier_assertion_rule_v1()
returns table(assertion_id bigint,release_id text,variation_id bigint,condition_id text,condition_name text,
 gene_symbol text,inheritance_mode text,penetrance_class text,penetrance_citation text,variant_name text,
 classification text,review_status text,review_stars smallint,last_evaluated date,
 chrom smallint,pos integer,ref text,alt text,equivalents jsonb)
language sql stable security definer set search_path=pg_catalog as $$
 select a.assertion_id,a.release_id,a.variation_id,c.condition_id,c.condition_name,c.gene_symbol,c.inheritance_mode,
  c.penetrance_class,c.penetrance_citation,a.variant_name,a.classification,a.review_status,a.review_stars,a.last_evaluated,
  a.grch38_chrom,a.grch38_pos,a.grch38_ref,a.grch38_alt,a.grch38_equivalents
 from public.clinical_assertions a
 join public.clinical_assertion_releases r on r.release_id=a.release_id
 join public.carrier_conditions c on c.condition_id=a.condition_id and c.gene_symbol=a.gene_symbol
 where r.retired_at is null
  and c.active and c.gene_validity_classification in ('Definitive','Strong')
  and c.synthetic=(r.source='synthetic')
  and a.classification in ('Pathogenic','Likely pathogenic','Pathogenic/Likely pathogenic')
  and a.review_stars>=2 and not a.conflict
 order by c.gene_symbol,a.grch38_pos,a.assertion_id
$$;
revoke all on function private.carrier_assertion_rule_v1() from public,anon,authenticated,inherit_upload_only,service_role;

-- The rule's rows for the application's legacy-file reader, and nothing else.
create function public.carrier_assertions_v1()
returns jsonb language sql stable security definer set search_path=pg_catalog as $$
 select coalesce(jsonb_agg(to_jsonb(r) order by r.gene_symbol,r.pos,r.assertion_id),'[]'::jsonb)
 from private.carrier_assertion_rule_v1() r
$$;

-- ---------------------------------------------------------------------------
-- The import door (service only): inactive conditions, one release
-- ---------------------------------------------------------------------------

create function public.import_clinical_assertion_release_v1(p_payload jsonb)
returns jsonb language plpgsql security definer set search_path=pg_catalog as $$
declare rel jsonb; c jsonb; a jsonb; existing public.carrier_conditions%rowtype; v_source text; v_release text;
 v_retired text[]; v_assertions integer:=0; v_conditions integer:=0; v_synthetic boolean;
begin
 if jsonb_typeof(p_payload) is distinct from 'object' or not (p_payload ?& array['release','conditions','assertions'])
  or p_payload-array['release','conditions','assertions']<>'{}'::jsonb
  or jsonb_typeof(p_payload->'conditions') is distinct from 'array'
  or jsonb_typeof(p_payload->'assertions') is distinct from 'array'
  or jsonb_array_length(p_payload->'conditions') not between 1 and 50
  or jsonb_array_length(p_payload->'assertions') not between 1 and 100000 then
  raise exception using errcode='22023',message='invalid_request'; end if;
 rel:=p_payload->'release';
 if jsonb_typeof(rel) is distinct from 'object' or not (rel ?& array['releaseId','source','sourceUrl','sourceSha256',
  'sourceBytes','sourcePublishedOn','retrievedAt','extractSha256','geneValidityUrl','geneValiditySha256','geneValidityCreatedOn'])
  or rel-array['releaseId','source','sourceUrl','sourceSha256','sourceBytes','sourcePublishedOn','retrievedAt',
   'extractSha256','geneValidityUrl','geneValiditySha256','geneValidityCreatedOn']<>'{}'::jsonb then
  raise exception using errcode='22023',message='invalid_request'; end if;
 v_source:=rel->>'source'; v_release:=rel->>'releaseId'; v_synthetic:=v_source='synthetic';
 perform 1 from public.clinical_assertion_releases where source=v_source for update;
 with retired as (update public.clinical_assertion_releases set retired_at=clock_timestamp()
  where source=v_source and retired_at is null returning release_id)
 select coalesce(array_agg(release_id order by release_id),'{}') into v_retired from retired;
 insert into public.clinical_assertion_releases(release_id,source,source_url,source_sha256,source_bytes,source_published_on,
  retrieved_at,extract_sha256,gene_validity_url,gene_validity_sha256,gene_validity_created_on)
 values(v_release,v_source,rel->>'sourceUrl',rel->>'sourceSha256',(rel->>'sourceBytes')::bigint,
  (rel->>'sourcePublishedOn')::date,(rel->>'retrievedAt')::timestamptz,rel->>'extractSha256',rel->>'geneValidityUrl',
  rel->>'geneValiditySha256',(rel->>'geneValidityCreatedOn')::date);
 for c in select value from jsonb_array_elements(p_payload->'conditions') loop
  if jsonb_typeof(c) is distinct from 'object' or not (c ?& array['conditionId','conditionName','geneSymbol','inheritanceMode',
   'geneValidityClassification','geneValidityClassifiedOn','geneValidityUrl'])
   or c-array['conditionId','conditionName','geneSymbol','inheritanceMode','geneValidityClassification',
    'geneValidityClassifiedOn','geneValidityUrl']<>'{}'::jsonb
   or ((c->>'conditionId') like 'SYNTHETIC:%') is distinct from v_synthetic then
   raise exception using errcode='22023',message='invalid_request'; end if;
  select * into existing from public.carrier_conditions where condition_id=c->>'conditionId' for update;
  if existing.condition_id is null then
   insert into public.carrier_conditions(condition_id,condition_name,gene_symbol,inheritance_mode,gene_validity_classification,
    gene_validity_classified_on,gene_validity_url,synthetic)
   values(c->>'conditionId',c->>'conditionName',c->>'geneSymbol',c->>'inheritanceMode',c->>'geneValidityClassification',
    (c->>'geneValidityClassifiedOn')::date,c->>'geneValidityUrl',v_synthetic);
  elsif (existing.condition_name,existing.inheritance_mode,existing.gene_validity_classification,
   existing.gene_validity_classified_on,existing.gene_validity_url) is distinct from
   (c->>'conditionName',c->>'inheritanceMode',c->>'geneValidityClassification',
    (c->>'geneValidityClassifiedOn')::date,c->>'geneValidityUrl') then
   -- What a reviewer approved has changed: a new revision, inactive again.
   update public.carrier_conditions set condition_name=c->>'conditionName',inheritance_mode=c->>'inheritanceMode',
    gene_validity_classification=c->>'geneValidityClassification',
    gene_validity_classified_on=(c->>'geneValidityClassifiedOn')::date,gene_validity_url=c->>'geneValidityUrl',
    registry_revision=existing.registry_revision+1,active=false,active_review_id=null,severity_class='unreviewed'
   where condition_id=existing.condition_id and gene_symbol=c->>'geneSymbol';
   if not found then raise exception using errcode='22023',message='invalid_request'; end if;
  elsif existing.gene_symbol<>c->>'geneSymbol' then raise exception using errcode='22023',message='invalid_request';
  end if;
  v_conditions:=v_conditions+1;
 end loop;
 for a in select value from jsonb_array_elements(p_payload->'assertions') loop
  if jsonb_typeof(a) is distinct from 'object' or not (a ?& array['variationId','conditionId','geneSymbol','variantName',
   'classification','reviewStatus','reviewStars','conflict','lastEvaluated','grch38','grch37','grch38Equivalents'])
   or a-array['variationId','conditionId','geneSymbol','variantName','classification','reviewStatus','reviewStars',
    'conflict','lastEvaluated','grch38','grch37','grch38Equivalents']<>'{}'::jsonb
   or jsonb_typeof(a->'grch38') is distinct from 'array' or jsonb_array_length(a->'grch38')<>4
   or (jsonb_typeof(a->'grch37')<>'null' and (jsonb_typeof(a->'grch37')<>'array' or jsonb_array_length(a->'grch37')<>4))
   or jsonb_typeof(a->'conflict') is distinct from 'boolean'
   or not exists(select 1 from jsonb_array_elements(p_payload->'conditions') x where x->>'conditionId'=a->>'conditionId') then
   raise exception using errcode='22023',message='invalid_request'; end if;
  insert into public.clinical_assertions(release_id,variation_id,condition_id,gene_symbol,variant_name,classification,
   review_status,review_stars,conflict,last_evaluated,grch38_chrom,grch38_pos,grch38_ref,grch38_alt,
   grch37_chrom,grch37_pos,grch37_ref,grch37_alt,grch38_equivalents)
  values(v_release,(a->>'variationId')::bigint,a->>'conditionId',a->>'geneSymbol',a->>'variantName',a->>'classification',
   a->>'reviewStatus',(a->>'reviewStars')::smallint,(a->>'conflict')::boolean,(a->>'lastEvaluated')::date,
   (a#>>'{grch38,0}')::smallint,(a#>>'{grch38,1}')::integer,a#>>'{grch38,2}',a#>>'{grch38,3}',
   (a#>>'{grch37,0}')::smallint,(a#>>'{grch37,1}')::integer,a#>>'{grch37,2}',a#>>'{grch37,3}',a->'grch38Equivalents');
  v_assertions:=v_assertions+1;
 end loop;
 return jsonb_build_object('releaseId',v_release,'retired',to_jsonb(v_retired),'conditions',v_conditions,'assertions',v_assertions);
exception when invalid_text_representation or numeric_value_out_of_range or datetime_field_overflow
 or invalid_datetime_format or check_violation or not_null_violation or foreign_key_violation or unique_violation then
 raise exception using errcode='22023',message='invalid_request';
end; $$;

-- ---------------------------------------------------------------------------
-- The review door (service only): a named person activates or withdraws
-- ---------------------------------------------------------------------------

create function public.review_carrier_condition_v1(p_condition_id text,p_registry_revision bigint,p_decision text,
 p_reviewer_name text,p_reviewer_role text,p_review_reference text,p_severity_class text default null)
returns bigint language plpgsql security definer set search_path=pg_catalog as $$
declare c public.carrier_conditions%rowtype; v_review bigint;
begin
 select * into c from public.carrier_conditions where condition_id=p_condition_id for update;
 if c.condition_id is null or c.registry_revision is distinct from p_registry_revision
  or p_decision is null or p_decision not in ('activate','deactivate') then
  raise exception using errcode='22023',message='invalid_request'; end if;
 if p_decision='activate' and (c.gene_validity_classification not in ('Definitive','Strong')
  or p_severity_class is null or p_severity_class not in ('serious','not_serious')
  -- ADR 0034: a sex-linked condition only when a reviewer has judged it serious.
  or (c.inheritance_mode='x_linked' and p_severity_class<>'serious')) then
  raise exception using errcode='55000',message='carrier_condition_not_activatable'; end if;
 insert into public.carrier_condition_reviews(condition_id,registry_revision,decision,reviewer_name,reviewer_role,
  review_reference,severity_class)
 values(c.condition_id,c.registry_revision,p_decision,p_reviewer_name,p_reviewer_role,p_review_reference,
  case when p_decision='activate' then p_severity_class end)
 returning review_id into v_review;
 if p_decision='activate' then
  update public.carrier_conditions set active=true,active_review_id=v_review,severity_class=p_severity_class
  where condition_id=c.condition_id;
 else
  update public.carrier_conditions set active=false,active_review_id=null where condition_id=c.condition_id;
 end if;
 return v_review;
exception when check_violation or not_null_violation then
 raise exception using errcode='22023',message='invalid_request';
end; $$;

-- ---------------------------------------------------------------------------
-- Portrait: the carrier reader over each person's current prepared source
-- ---------------------------------------------------------------------------

create function private.family_portrait_carrier_side_v1(p_account uuid,p_subject uuid,p_loci jsonb)
returns jsonb language plpgsql security definer set search_path=pg_catalog as $$
declare s jsonb; f public.genome_files%rowtype; v jsonb; o jsonb;
begin
 s:=private.family_portrait_prepared_source_v1(p_account,p_subject);
 if s->'source' is null or s->'source'='null'::jsonb then return null; end if;
 select * into f from public.genome_files where id=(s#>>'{source,fileId}')::uuid and subject_id=p_subject and user_id=p_account;
 if f.id is null or f.upload_revision::text is distinct from s#>>'{source,revision}' or f.sha256 is distinct from s#>>'{source,rawSha256}' then
  raise exception using errcode='42501',message='not_found'; end if;
 -- Only the rule's loci are read; the caller supplies none.
 select coalesce(jsonb_agg(jsonb_build_object('chrom',x.chrom,'pos',x.pos,'ref',x.ref,'alt',x.alt,'genotype',x.genotype)
  order by x.chrom,x.pos,x.id),'[]'::jsonb) into v
 from (select distinct uv.id,uv.chrom,uv.pos,uv.ref,uv.alt,uv.genotype
  from jsonb_to_recordset(p_loci) l(chrom smallint,pos integer)
  join public.user_variants uv on uv.subject_id=p_subject and uv.chrom=l.chrom and uv.pos=l.pos
  where uv.file_id=f.id and uv.user_id=p_account) x;
 select coalesce(jsonb_agg(jsonb_build_object('chrom',x.chrom,'pos',x.pos,'ref',x.ref,'alt',x.alt,'genotype',x.genotype,
  'usable',x.usable) order by x.chrom,x.pos,x.source_line),'[]'::jsonb) into o
 from (select distinct rc.source_line,rc.chrom,rc.pos,rc.ref,rc.alt,rc.genotype,rc.usable
  from jsonb_to_recordset(p_loci) l(chrom smallint,pos integer)
  join public.report_observed_calls rc on rc.file_id=f.id and rc.chrom=l.chrom and rc.pos=l.pos
  where rc.subject_id=p_subject and rc.user_id=p_account and rc.source_sha256=f.sha256
   and rc.extraction_version='vcf-literal-diploid-snp-v1' and rc.source_build=f.build) x;
 return jsonb_build_object('fileId',f.id,'runs',jsonb_build_object('status',f.roh_status,'reason',f.roh_reason,
  'totalBases',f.roh_total_bases,'coveredBases',f.roh_covered_bases,'fraction',f.roh_fraction),
  'variants',v,'observed',o);
end; $$;

-- The page captures a readiness receipt first; this reader proves the same
-- receipt again (both current Portrait grants, sessions, acknowledgements,
-- independent logins and exact prepared sources, under the same locks) and
-- only then reads. It returns null on any difference, and for a pair whose
-- sources are not both canonical. The page's last await still re-confirms
-- the receipt before anything renders.
create function public.family_portrait_carrier_calls_v1(p_account_id uuid,p_session_id uuid,p_pair_id uuid,
 p_counterpart_account_id uuid,p_expected text)
returns jsonb language plpgsql security definer set search_path=pg_catalog as $$
declare readiness jsonb; authority jsonb; rule jsonb; loci jsonb; sa jsonb; sb jsonb;
begin
 if p_expected is null or p_expected!~'^[0-9a-f]{64}$' then return null; end if;
 readiness:=public.family_portrait_source_readiness_v1(p_account_id,p_session_id,p_pair_id,p_counterpart_account_id,p_expected);
 if readiness is null or readiness->>'receipt' is distinct from p_expected or readiness->>'kind'<>'canonical' then return null; end if;
 authority:=private.family_portrait_authority_v1(p_account_id,p_session_id,p_pair_id,p_counterpart_account_id);
 if authority is null or (authority->>'strong')::boolean is not true
  or authority#>>'{subjectA,id}' is distinct from readiness#>>'{a,subjectId}'
  or authority#>>'{subjectB,id}' is distinct from readiness#>>'{b,subjectId}' then return null; end if;
 select coalesce(jsonb_agg(to_jsonb(r) order by r.gene_symbol,r.pos,r.assertion_id),'[]'::jsonb) into rule
 from private.carrier_assertion_rule_v1() r;
 select coalesce(jsonb_agg(distinct jsonb_build_object('chrom',l.chrom,'pos',l.pos)),'[]'::jsonb) into loci from (
  select (x->>'chrom')::smallint chrom,(x->>'pos')::integer pos from jsonb_array_elements(rule) x
  union select (x->>'chrom')::smallint,(e->>0)::integer from jsonb_array_elements(rule) x
   cross join lateral jsonb_array_elements(x->'equivalents') e) l;
 if jsonb_array_length(rule)>0 then
  if (readiness#>>'{a,hasPreparedSource}')::boolean then
   sa:=private.family_portrait_carrier_side_v1((authority#>>'{subjectA,accountId}')::uuid,(authority#>>'{subjectA,id}')::uuid,loci);
  end if;
  if (readiness#>>'{b,hasPreparedSource}')::boolean then
   sb:=private.family_portrait_carrier_side_v1((authority#>>'{subjectB,accountId}')::uuid,(authority#>>'{subjectB,id}')::uuid,loci);
  end if;
 end if;
 return jsonb_build_object('receipt',p_expected,'assertions',rule,
  'a',jsonb_build_object('subjectId',readiness#>>'{a,subjectId}','source',sa),
  'b',jsonb_build_object('subjectId',readiness#>>'{b,subjectId}','source',sb));
exception when lock_not_available or insufficient_privilege or object_not_in_prerequisite_state or invalid_text_representation then return null;
end; $$;

-- ---------------------------------------------------------------------------
-- Runs of homozygosity for a prepared source, measured at ingest
-- ---------------------------------------------------------------------------

create function public.record_own_normalization_runs_v1(p_account_id uuid,p_session_id uuid,p_file_id uuid,p_runs jsonb)
returns boolean language plpgsql security definer set search_path=pg_catalog,private as $$
declare f public.genome_files%rowtype;
begin
 if jsonb_typeof(p_runs) is distinct from 'object' or coalesce(p_runs->>'status','') not in ('measured','not_measurable')
  or (p_runs->>'status'='measured' and (not (p_runs ?& array['status','totalBases','coveredBases','fraction'])
   or p_runs-array['status','totalBases','coveredBases','fraction']<>'{}'::jsonb
   or jsonb_typeof(p_runs->'totalBases')<>'number' or jsonb_typeof(p_runs->'coveredBases')<>'number'
   or jsonb_typeof(p_runs->'fraction')<>'number'))
  or (p_runs->>'status'='not_measurable' and (not (p_runs ?& array['status','reason'])
   or p_runs-array['status','reason']<>'{}'::jsonb)) then
  raise exception using errcode='22023',message='invalid_request'; end if;
 select * into f from public.genome_files where id=p_file_id and user_id=p_account_id;
 if f.id is null or f.subject_id is null then raise exception using errcode='42501',message='not_found'; end if;
 -- The same live session, store consent and subject authority the upload used.
 perform private.own_upload_store_authority_v1(p_account_id,p_session_id,f.subject_id);
 select * into f from public.genome_files where id=p_file_id and user_id=p_account_id for update;
 if f.single_logical_sample_verified_at is null or f.structural_validator_version is distinct from 'single-logical-sample-v1'
  or f.normalization_completed_at is null or f.normalization_source_revision is distinct from f.upload_revision
  or not exists(select 1 from private.own_normalization_runs n where n.file_id=f.id and n.account_id=p_account_id and n.state='complete')
  or exists(select 1 from private.genome_file_deletions where file_id=f.id) then
  raise exception using errcode='42501',message='not_found'; end if;
 -- Measured once: a stored measure is never replaced.
 if f.roh_status is not null then return false; end if;
 update public.genome_files set
  roh_status=p_runs->>'status',
  roh_reason=case when p_runs->>'status'='not_measurable' then p_runs->>'reason' end,
  roh_total_bases=case when p_runs->>'status'='measured' then (p_runs->>'totalBases')::bigint end,
  roh_covered_bases=case when p_runs->>'status'='measured' then (p_runs->>'coveredBases')::bigint end,
  roh_fraction=case when p_runs->>'status'='measured' then round((p_runs->>'fraction')::numeric,6) end,
  roh_measured_at=clock_timestamp()
 where id=f.id;
 return true;
exception when check_violation or invalid_text_representation or numeric_value_out_of_range then
 raise exception using errcode='22023',message='invalid_request';
end; $$;


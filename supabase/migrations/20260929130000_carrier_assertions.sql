-- A condition is active only through a recorded activation of its current
-- revision; any other change to what was reviewed deactivates it.
create function private.guard_carrier_condition_v1()
returns trigger language plpgsql security definer set search_path=pg_catalog as $$
declare r public.carrier_condition_reviews%rowtype;
begin
 if tg_op='UPDATE' and (new.condition_id,new.gene_symbol,new.synthetic) is distinct from
  (old.condition_id,old.gene_symbol,old.synthetic) then
  raise exception using errcode='55000',message='carrier_condition_identity_immutable'; end if;
 if new.active then
  select * into r from public.carrier_condition_reviews where review_id=new.active_review_id;
  if r.review_id is null or r.condition_id<>new.condition_id or r.decision<>'activate'
   or r.registry_revision<>new.registry_revision or r.severity_class is distinct from new.severity_class then
   raise exception using errcode='42501',message='carrier_condition_review_required'; end if;
 end if;
 return new;
end; $$;
revoke all on function private.guard_carrier_condition_v1() from public,anon,authenticated,inherit_upload_only,service_role;
create trigger carrier_conditions_reviewed before insert or update on public.carrier_conditions
 for each row execute function private.guard_carrier_condition_v1();


-- Reviewed carrier assertions (docs/carrier-importer-design.md; owner decisions
-- of 28 September 2026, docs/protocol/decisions.md).
--
-- Until now the carrier-pair reader returned nothing by construction: the
-- legacy `ref_variants` table is keyed by rsID, carries one ALT per rsID and
-- no condition, review status or release, so none of its labels could be
-- trusted with a personal result. This migration adds the tables that can
-- hold a reviewed assertion and the one rule that reads them:
--
--   - `clinical_assertion_releases`: one pinned source release (ClinVar's
--     monthly release, or a synthetic test release), with the SHA-256 of the
--     file it was read from and of ClinGen's gene-disease snapshot. At most
--     one current release per source; importing a new one retires the old.
--   - `carrier_conditions`: one condition per gene, keyed by MONDO id, with
--     its inheritance mode (not null, checked), ClinGen's gene-disease
--     classification, a penetrance class and a severity class. Written
--     INACTIVE by the importer; only a named reviewer activates one.
--   - `carrier_condition_reviews`: the append-only record of each review.
--   - `clinical_assertions`: one row per classified allele and condition,
--     keyed by the exact GRCh38 allele (chromosome, position, REF, ALT; simple
--     and left-aligned), with ClinVar's GRCh37 placement of the same allele,
--     the other GRCh38 spellings of an insertion or deletion inside a repeat,
--     the classification, review status and stars, the conflict flag and the
--     date ClinVar last evaluated it.
--
-- The production rule (`private.carrier_assertion_rule_v1`) returns an
-- assertion only when ALL of these hold: pathogenic or likely pathogenic, two
-- review stars or more, no conflict, a current (not retired) release, an
-- active reviewed condition whose ClinGen link is Definitive or Strong, and a
-- gene that matches the condition's. Anything else is not covered, never "not
-- a carrier". Nothing reads `ref_variants` any more for a carrier result.
--
-- Two readers use the rule, both service-only: the legacy-file reader in the
-- application, and `public.family_portrait_carrier_calls_v1`, which reads each
-- Portrait person's CURRENT PREPARED SOURCE at the rule's loci only, under the
-- exact authority `family_portrait_source_readiness_v1` already proves.
--
-- Runs of homozygosity for a prepared source: the carrier rule needs each
-- file's runs measure, which the legacy processing route stores and the
-- prepared path never did. `public.record_own_normalization_runs_v1` lets the
-- normalization route store the measure it takes from the verified bytes,
-- once, after the source is published (D-030: measured at ingest, never
-- re-derived by a reader).
--
-- No person's data is written by this migration, and every condition it
-- could create starts inactive. The ClinVar import itself is a separate
-- guarded apply generated by `scripts/build-carrier-assertions.ts --emit-sql`.

-- ---------------------------------------------------------------------------
-- Allele keys
-- ---------------------------------------------------------------------------

-- One definition of a keyable allele, shared with src/lib/family/allele-key.ts:
-- a single-letter change, or an insertion or deletion that shares exactly its
-- first letter with the other spelling and cannot move one base left (its
-- anchor differs from the last letter it adds or removes).
create function private.carrier_allele_key_valid_v1(p_ref text,p_alt text)
returns boolean language sql immutable set search_path='' as $$
 select coalesce(p_ref ~ '^[ACGT]+$' and p_alt ~ '^[ACGT]+$' and p_ref<>p_alt and (
  (length(p_ref)=1 and length(p_alt)=1)
  or (length(p_alt)=1 and length(p_ref)>1 and left(p_ref,1)=p_alt and right(p_ref,1)<>p_alt)
  or (length(p_ref)=1 and length(p_alt)>1 and left(p_alt,1)=p_ref and right(p_alt,1)<>p_ref)),false)
$$;

-- The other spellings of one left-aligned insertion or deletion: each a
-- [position, REF, ALT] triple to the right of the key, strictly increasing,
-- the same shape and lengths. A single-letter change has none.
create function private.carrier_equivalents_valid_v1(p_equivalents jsonb,p_pos integer,p_ref text,p_alt text)
returns boolean language plpgsql immutable set search_path='' as $$
declare e jsonb; previous integer:=p_pos;
begin
 if jsonb_typeof(p_equivalents) is distinct from 'array' then return false; end if;
 if length(p_ref)=1 and length(p_alt)=1 then return p_equivalents='[]'::jsonb; end if;
 if jsonb_array_length(p_equivalents)>64 then return false; end if;
 for e in select value from jsonb_array_elements(p_equivalents) loop
  if jsonb_typeof(e) is distinct from 'array' or jsonb_array_length(e)<>3
   or jsonb_typeof(e->0)<>'number' or jsonb_typeof(e->1)<>'string' or jsonb_typeof(e->2)<>'string'
   or (e->>0)!~'^[1-9][0-9]{0,9}$' or (e->>0)::bigint<=previous or (e->>0)::bigint>2147483647
   or (e->>1)!~'^[ACGT]+$' or (e->>2)!~'^[ACGT]+$'
   or length(e->>1)<>length(p_ref) or length(e->>2)<>length(p_alt)
   or left(e->>1,1)<>left(e->>2,1) then return false; end if;
  previous:=(e->>0)::integer;
 end loop;
 return true;
end; $$;


// Generates e2e/fixtures/neanderthal-grch38.vcf: a synthetic single-sample
// GRCh38 VCF that covers a deterministic subset of the Neanderthal panel's
// sites, so the TEST-LOCAL Neanderthal estimate (share, bootstrap range,
// covered-site count, panel+version, resolution limit — brief §4.6, G4.4)
// becomes reachable in a browser instead of only unit-tested.
//
//   pnpm exec tsx e2e/fixtures/generate-neanderthal-vcf.ts
//
// It describes no real person. Every position and both alleles of every row
// are copied out of the shipped panel (`data/ref/neanderthal/sites.json`,
// provenance in the PROVENANCE.md beside it). The generator invents no
// coordinate or base; it only chooses, from a seeded draw, which of each
// site's two panel alleles the synthetic sample carries and whether it is
// heterozygous or homozygous. REF is set to the site's `other` letter and ALT
// to its `archaic` letter, so carrying the Neanderthal-derived allele is the
// ALT allele; the REF column carries no claim about the GRCh38 reference base.
//
// The output is byte-identical across runs. After writing, the script runs the
// real estimator (`src/lib/genome/neanderthal.ts`) over the rows and fails
// unless enough sites are covered and the estimate has a usable, non-degenerate
// range — so a drift that makes the fixture stop covering the panel is caught
// at generation.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { NEANDERTHAL_SITES, estimateNeanderthal, type NeanderthalCall } from "../../src/lib/genome/neanderthal";

export const FIXTURE_NAME = "neanderthal-grch38.vcf";

/** How many of the panel's sites the synthetic sample carries a call at. */
export const COVERED = 180;
/** Seed for the per-site draw; a constant, so the file is byte-stable. */
export const SEED = 7;

function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

interface Row { chrom: number; pos: number; rsid: string; ref: string; alt: string; gt: string }

/** The covered sites and their synthetic genotypes, chosen deterministically. */
export function rows(): Row[] {
  const random = mulberry32(SEED);
  const chosen = NEANDERTHAL_SITES.slice(0, COVERED);
  return chosen.map((site) => {
    // ~45% of covered sites carry a Neanderthal-derived allele, split between
    // heterozygous and homozygous; the rest carry two copies of the other
    // allele. A spread of outcomes gives the bootstrap a non-degenerate range.
    const draw = random();
    const gt = draw < 0.30 ? "0/1" : draw < 0.45 ? "1/1" : "0/0";
    return { chrom: site.chrom, pos: site.pos38, rsid: site.rsid, ref: site.other, alt: site.archaic, gt };
  });
}

export function render(): string {
  const header = [
    "##fileformat=VCFv4.2",
    `##source=Inherit deterministic synthetic fixture; no real person; seed ${SEED}; generated by e2e/fixtures/generate-neanderthal-vcf.ts`,
    "##reference=GRCh38",
    "##inheritNeanderthalPanel=data/ref/neanderthal/sites.json; every POS/REF/ALT is a shipped panel site",
    "##inheritAlleleEncoding=ALT is the site's Neanderthal-derived (archaic) allele, REF the other panel allele; REF is not a claim about the GRCh38 reference base",
    "##FORMAT=<ID=GT,Number=1,Type=String,Description=\"Genotype\">",
    "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tSAMPLE1",
  ];
  const body = rows().map((row) =>
    `chr${row.chrom}\t${row.pos}\t${row.rsid}\t${row.ref}\t${row.alt}\t50\tPASS\t.\tGT\t${row.gt}`);
  return `${[...header, ...body].join("\n")}\n`;
}

/** Run the real estimator over the rows and fail on a fixture that no longer works. */
export function verify(content: string): void {
  const calls: NeanderthalCall[] = content.split("\n").filter((line) => line && !line.startsWith("#")).map((line) => {
    const [chrom, pos, , ref, alt, , , , , sample] = line.split("\t");
    const alleles = sample.split(/[/|]/).map((copy) => (copy === "0" ? ref : alt));
    return { chrom: Number(chrom.replace("chr", "")), pos: Number(pos), ref, alt, genotype: alleles.join("/"), usable: true };
  });
  const result = estimateNeanderthal(calls, "vcf-literal");
  if (result.coveredSites < 150) throw new Error(`too few covered sites: ${result.coveredSites}`);
  if (result.estimate === null || result.estimate <= 0 || result.estimate >= 1) throw new Error(`estimate out of range: ${result.estimate}`);
  if (result.interval === null) throw new Error("fixture produced no bootstrap range");
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const content = render();
  verify(content);
  const out = path.join(path.dirname(fileURLToPath(import.meta.url)), FIXTURE_NAME);
  fs.writeFileSync(out, content);
  const result = estimateNeanderthal(
    rows().map((row) => ({ chrom: row.chrom, pos: row.pos, ref: row.ref, alt: row.alt,
      genotype: row.gt.split("/").map((c) => (c === "0" ? row.ref : row.alt)).join("/"), usable: true })),
    "vcf-literal",
  );
  console.log(`Wrote ${FIXTURE_NAME}: sha256 ${crypto.createHash("sha256").update(content).digest("hex")}`);
  console.log(`covered ${result.coveredSites}, archaic ${result.archaicSites}, estimate ${result.estimate}, interval ${JSON.stringify(result.interval)}`);
}

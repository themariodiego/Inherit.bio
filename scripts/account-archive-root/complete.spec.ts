import { randomBytes, randomUUID } from "node:crypto";
import { readFileSync } from "node:fs";
import path from "node:path";
import { expect, test } from "../../e2e/audited-test";
import { adminClient, createConfirmedUser } from "../../e2e/helpers";
import { generateOwnFileWithChosenReports, uploadOwnFilePrepared } from "../../e2e/own-report-helpers";
import { exerciseCompleteAccountArchiveDelivery, exerciseCompleteAccountArchiveDisposal } from "../../e2e/helpers/account-archive-complete-journey";
import { assertTestAccountArchiveFixtureAdmission } from "../../src/lib/exports/account-archive-test-admission";
import { readRootAccountArchiveCheckpoint, saveRootAccountArchiveCheckpoint } from "./checkpoint";

function selectedJobSecret(): string {
  const value = process.env.JOBS_SECRET;
  if (!value || value.length > 4096) throw new Error("root_account_archive_job_unavailable");
  return value;
}

// Root selects these two exact phases in separate owned invocations. The
// second is not runnable until the first actual native 24-hour job is due.
// No test changes a clock, deadline, configuration, source, grant or consent.
test("complete account archive: fresh real TEST request, generated bytes, browser ACK and exact ZIP", async ({ page }) => {
  test.setTimeout(300_000);
  const signal = AbortSignal.timeout(300_000), jobSecret = selectedJobSecret();
  await assertTestAccountArchiveFixtureAdmission({ signal });
  const password = randomBytes(32).toString("base64url");
  const email = `complete-archive-${randomUUID()}@e2e.local`;
  const accountId = await createConfirmedUser(email, password, { jurisdiction: null });
  await page.goto("/auth/sign-in?next=%2Fgenome%2Fme%2Freports");
  const user = await adminClient().auth.admin.getUserById(accountId);
  expect(user.error).toBeNull();
  expect(user.data.user?.email).toBe(email);
  await page.getByLabel("Email").fill(email);
  await page.getByLabel("Password").fill(password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL("http://localhost:3100/settings?next=%2Fgenome%2Fme%2Freports");
  const jurisdiction = page.locator('[data-slot="jurisdiction"]');
  await jurisdiction.getByLabel("Country you live in").selectOption("GB");
  await jurisdiction.getByLabel("The place I chose is where I live.").check();
  const declared = page.waitForResponse(response => new URL(response.url()).pathname === "/api/settings/jurisdiction"
    && response.request().method() === "PUT");
  await jurisdiction.getByRole("button", { name: "Save country", exact: true }).click();
  expect((await declared).status()).toBe(200);
  await expect(page).toHaveURL("http://localhost:3100/genome/me/reports");
  const originals: { fileId: string; bytes: Uint8Array }[] = [];
  for (const name of ["tiny-grch38.vcf", "personal-previews-grch38.vcf"]) {
    const filename = path.join(process.cwd(), "e2e/fixtures", name);
    const fileId = await uploadOwnFilePrepared(page, filename, { fileType: "vcf" });
    originals.push({ fileId, bytes: readFileSync(filename) });
  }
  await generateOwnFileWithChosenReports(page, originals[0].fileId, ["reports.polygenic"]);
  const source = await adminClient().from("genome_files").select("id,subject_id,user_id")
    .in("id", originals.map(value => value.fileId)).eq("user_id", accountId);
  expect(source.error).toBeNull();
  expect(source.data?.map(value => value.id).sort()).toEqual(originals.map(value => value.fileId).sort());
  const subjects = [...new Set((source.data ?? []).map(value => value.subject_id))];
  expect(subjects).toHaveLength(1);
  const delivery = await exerciseCompleteAccountArchiveDelivery({ page, accountId, jobSecret,
    originals, expectedSubjects: subjects, signal });
  saveRootAccountArchiveCheckpoint({ version: "account-archive-root-delivery-checkpoint-v1", accountId, delivery });
});

test("complete account archive: original due transition and whole current-object disposal ACK", async ({ page }) => {
  test.setTimeout(300_000);
  const checkpoint = readRootAccountArchiveCheckpoint(), signal = AbortSignal.timeout(300_000);
  const proof = await exerciseCompleteAccountArchiveDisposal({ page, accountId: checkpoint.accountId,
    jobSecret: selectedJobSecret(), delivery: checkpoint.delivery, signal });
  expect(proof).toEqual({ version: "account-archive-test-current-object-disposal-proof-v1",
    exportId: checkpoint.delivery.exportId, attemptId: checkpoint.delivery.attemptId,
    allocationCount: checkpoint.delivery.allocations.count, identitySha256: checkpoint.delivery.allocations.identitySha256,
    disposition: "current-object-absent", historyScope: "current-object-only" });
});
